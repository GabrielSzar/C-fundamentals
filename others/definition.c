/**
 * @brief Realiza a soma de dois números inteiros.
 *
 * Esta função recebe dois valores inteiros, calcula a adição
 * entre eles e retorna o resultado final.
 *
 * @param a O primeiro número a ser somado.
 * @param b O segundo número a ser somado.
 * @return O resultado da soma de a e b.
 */
int Sum(int a, int b)
{
    return a + b;
}
